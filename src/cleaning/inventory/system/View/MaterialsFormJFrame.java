    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
        String name = nameField.getText();
        int quantity = Integer.parseInt(quantityField.getText());
        int reorderLevel = Integer.parseInt(reorderLevelField.getText());
        String description = descriptionField.getText();

        Integer supplierId = null;
        if (!supplierIDField.getText().trim().isEmpty()) {
            supplierId = Integer.parseInt(supplierIDField.getText().trim());
        }

        boolean success = materialController.addMaterial(name, quantity, reorderLevel, supplierId, description);

        if (success) {
            loadMaterialsIntoTable();
            clearFields();
            JOptionPane.showMessageDialog(this, "Material added!");
        } else {
            JOptionPane.showMessageDialog(this, "Failed to add material. Check your input.");
        }
    }//GEN-LAST:event_addButtonActionPerformed

    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
            if (selectedMaterialId == -1) {
            JOptionPane.showMessageDialog(this, "Select a material from the table first.");
            return;
        }

        Integer supplierId = null;
        if (!supplierIDField.getText().trim().isEmpty()) {
            supplierId = Integer.parseInt(supplierIDField.getText().trim());
        }

        Materials updated = new Materials(
            selectedMaterialId,
            nameField.getText(),
            Integer.parseInt(quantityField.getText()),
            Integer.parseInt(reorderLevelField.getText()),
            supplierId,
            descriptionField.getText()
        );

        boolean success = materialController.updateMaterial(updated);

        if (success) {
            loadMaterialsIntoTable();
            clearFields();
            JOptionPane.showMessageDialog(this, "Material updated!");
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update material.");
        }
    }//GEN-LAST:event_updateButtonActionPerformed

