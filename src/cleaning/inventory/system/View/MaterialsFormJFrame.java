    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed
            if (selectedMaterialId == -1) {
            JOptionPane.showMessageDialog(this, "Select a material from the table first.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Delete this material?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            boolean success = materialController.deleteMaterial(selectedMaterialId);
            if (success) {
                loadMaterialsIntoTable();
                clearFields();
                JOptionPane.showMessageDialog(this, "Material deleted!");
            } else {
                JOptionPane.showMessageDialog(this, "Failed to delete material.");
            }
        }      // TODO add your handling code here:
    }//GEN-LAST:event_deleteButtonActionPerformed

