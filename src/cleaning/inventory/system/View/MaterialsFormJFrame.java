    private void loadMaterialsIntoTable() {
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
        new Object[]{"ID", "Name", "Stock", "Reorder Level", "Supplier ID", "Description"}, 0
    );

    for (Materials m : materialController.getAllMaterials()) {
        model.addRow(new Object[]{
            m.getMaterial_id(), m.getName(), m.getQuantity_in_stock(),
            m.getReorder_level(), m.getSupplier_id(), m.getDescription()
        });
    }

    jTable1.setModel(model);
}

