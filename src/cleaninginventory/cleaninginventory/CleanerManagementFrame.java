    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {                                          
        // TODO add your handling code here:
        int selectedRow = tblCleaners.getSelectedRow();
        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Please select a cleaner to delete.", "No Selection",
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        int cleanerId = (int) tblCleaners.getValueAt(selectedRow, 0);

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
            "Are you sure you want to delete this cleaner?", "Confirm Delete", 
            javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            CleanerDAO dao = new CleanerDAO();
            boolean success = dao.deleteCleaner(cleanerId);
            if (success) {
            loadCleanersIntoTable();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "Cannot delete — this cleaner has existing stock issuance history.", "Delete Blocked", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }   
    }                                         

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {                                          
        // TODO add your handling code here:
        int selectedRow = tblCleaners.getSelectedRow();
        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Please select a cleaner to update.", "No Selection",
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        int cleanerId = (int) tblCleaners.getValueAt(selectedRow, 0);

        Cleaner c = new Cleaner();
        c.setCleanerId(cleanerId);
        c.setFirstName(txtFirstName.getText().trim());
        c.setLastName(txtLastName.getText().trim());
        c.setEmployeeNumber(txtEmployeeNumber.getText().trim());
        c.setDepartment(txtDepartment.getText().trim());

        CleanerDAO dao = new CleanerDAO();
        boolean success = dao.updateCleaner(c);

        if (success) {
            loadCleanersIntoTable();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Update failed.", "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }                                         

