    private void loadCleanersIntoTable() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblCleaners.getModel();
        model.setRowCount(0);

        CleanerDAO dao = new CleanerDAO();
        List<Cleaner> cleaners = dao.getAllCleaners();

        for (Cleaner c : cleaners) {
            model.addRow(new Object[]{
                c.getCleanerId(), 
                c.getFirstName(), 
                c.getLastName(),
                c.getEmployeeNumber(), 
                c.getDepartment()});
        }
    }
    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {                                       
        // TODO add your handling code here:
        String first = txtFirstName.getText().trim();
        String last = txtLastName.getText().trim();
        String empNum = txtEmployeeNumber.getText().trim();
        String dept = txtDepartment.getText().trim();

        if (first.isEmpty() || last.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "First and last name are required.", "Validation Error", 
                    javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
        }

        Cleaner c = new Cleaner();
        c.setFirstName(first);
        c.setLastName(last);
        c.setEmployeeNumber(empNum);
        c.setDepartment(dept);

        CleanerDAO dao = new CleanerDAO();
        boolean success = dao.addCleaner(c);

        if (success) {
            loadCleanersIntoTable();
            txtFirstName.setText("");
            txtLastName.setText("");
            txtEmployeeNumber.setText("");
            txtDepartment.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Failed to add cleaner.", "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }                                      

